"""The natural-selection demo: the daily loop in a simulated world, against a no-learning baseline.

The same `SimulatedWorld` (same hidden truths, same seed) is run twice for `days` days:
- `whynot`: the real daily loop (exploit what sells in a new format, explore far away, pause losers);
- `random`: the same loop, rules and budget, but new ideas drawn at random.
The difference between the two is what the agency's learning is worth in that world.

Ads are scripts only by default (`LabelProducer`, no model call): the selection depends on the idea, not the
render. `selection.json` (`docs/SELECTION_TREE.md`) is what the demo page draws: every ad as a node with its
parent, its views and conversions, and the day-by-day curves of both campaigns. Everything is labelled simulated.
"""

import json
from datetime import date, timedelta
from pathlib import Path
from typing import Any

from whynot.agency.daily import DailyConfig, run_day
from whynot.agency.memory import AdRecord, Memory
from whynot.create.trends import FORMATS
from whynot.run.autopilot import Level, Policy, Rules
from whynot.run.insights import SimulatedWorld

LABEL = "Simulated campaign: performance numbers are generated by a model, not real Meta results"
POLICIES = ("whynot", "random")


class LabelProducer:
    """An ad as a script label only (no model call, no render): enough for the selection, free."""

    def make(self, p: dict[str, Any], name_prefix: str, *, avoid: list[tuple[str, str]] | None = None
             ) -> dict[str, Any]:
        return {"brief": {"hook": f"{p['format']} · {p['angle']}", "voice": ""},
                "file": {"path": f"{name_prefix}-{p['format']}.mp4"}}


class WorldLauncher:
    """Launching an ad in the simulated world: it starts getting (simulated) results the next day."""

    simulated = True

    def __init__(self, world: SimulatedWorld):
        self.world = world

    def launch(self, rec: AdRecord, budget_eur: float) -> str:
        self.world.register(rec.key, (rec.format, rec.persona, rec.angle))
        return rec.key

    def pause(self, rec: AdRecord) -> None:
        return None


def _nodes(memory: Memory, start: date) -> list[dict[str, Any]]:
    out = []
    for r in sorted(memory.ads.values(), key=lambda r: (r.day, r.key)):
        paused = next((n.split(" ", 1)[0] for n in r.notes if " paused:" in n), None)
        out.append({"id": r.key, "day": (date.fromisoformat(r.day) - start).days + 1, "parent": r.parent,
                    "format": r.format, "persona": r.persona, "angle": r.angle, "hook": r.hook, "status": r.status,
                    "why": r.why, "impressions": sum(m.impressions for m in r.metrics),
                    "clicks": sum(m.clicks for m in r.metrics), "conversions": r.conversions, "spend_eur": r.spend,
                    "cpa_eur": round(r.cpa, 2) if r.cpa is not None else None,
                    "paused_day": (date.fromisoformat(paused) - start).days + 1 if paused else None})
    return out


def _timeline(memory: Memory, start: date, days: int) -> list[dict[str, Any]]:
    out = []
    for i in range(days):
        d = (start + timedelta(days=i)).isoformat()
        rows = [m for r in memory.ads.values() for m in r.metrics if m.day == d]
        spend = sum(m.spend_eur for m in rows)
        imp, conv = sum(m.impressions for m in rows), sum(m.conversions for m in rows)
        out.append({"day": i + 1, "live": len(rows), "spend_eur": round(spend, 2), "impressions": imp,
                    "conversions": conv, "views_per_eur": round(imp / spend, 1) if spend else 0.0,
                    "conversions_per_100_eur": round(100 * conv / spend, 2) if spend else 0.0})
    return out


def _last_week(timeline: list[dict[str, Any]]) -> float:
    week = timeline[-7:]
    spend = sum(t["spend_eur"] for t in week)
    return round(100 * sum(t["conversions"] for t in week) / spend, 2) if spend else 0.0


def run_selection(run_dir: Path, strategy: Any, *, days: int = 21, seed: int = 0, start: date = date(2026, 11, 1),
                  target_live: int = 4, max_new: int = 2, budget_per_ad_eur: float = 5.0, producer: Any = None,
                  app: dict[str, Any] | None = None, say: Any = print) -> dict[str, Any]:
    run_dir = Path(run_dir)
    formats = [f.id for f in FORMATS]
    pairs = [(a.persona, a.id) for a in strategy.angles]
    out: dict[str, Any] = {"simulated": True, "label": LABEL, "app": app or {}, "days": days,
                           "budget_per_ad_eur": budget_per_ad_eur, "policies": {}}
    best = None
    for name in POLICIES:
        world = SimulatedWorld(seed=seed, daily_budget_eur=budget_per_ad_eur)
        folder = f"agency-sim/{name}"
        cfg = DailyConfig(target_live=target_live, max_new=max_new, budget_per_ad_eur=budget_per_ad_eur,
                          rules=Rules(min_spend_eur=3 * budget_per_ad_eur), idea_policy=name, folder_name=folder)
        policy = Policy(Level.AUTOPILOT, target_live * budget_per_ad_eur, first_live_approved=True)
        mem_path = run_dir / folder / "memory.json"
        if mem_path.exists():
            mem_path.unlink()  # a fresh campaign each time: the demo must be reproducible
        for i in range(days):
            run_day(run_dir, start + timedelta(days=i), source=world, producer=producer or LabelProducer(),
                    launcher=WorldLauncher(world), policy=policy, strategy=strategy, cfg=cfg, say=lambda s: None)
        memory = Memory(mem_path)
        out["policies"][name] = {"nodes": _nodes(memory, start), "timeline": _timeline(memory, start, days)}
        best = world.best(formats, pairs)
        say(f"{name}: {len(memory.ads)} ads, last week {_last_week(out['policies'][name]['timeline'])} "
            f"conversions per €100 (simulated)")
    assert best is not None
    out["truth"] = {"best_format": best[0], "best_persona": best[1], "best_angle": best[2]}
    w, r = (_last_week(out["policies"][n]["timeline"]) for n in POLICIES)
    found = [n for n in out["policies"]["whynot"]["nodes"] if (n["format"], n["persona"], n["angle"]) == best]
    out["summary"] = {"whynot_conversions_per_100_eur_last_week": w, "random_conversions_per_100_eur_last_week": r,
                      "whynot_found_best_on_day": found[0]["day"] if found else None}
    path = run_dir / "agency-sim" / "selection.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(out, indent=1, ensure_ascii=False))
    return out
