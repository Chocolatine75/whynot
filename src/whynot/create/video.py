"""Deterministic video renderer: a `VideoBrief` → a 9:16 MP4 (1080×1920, 30 fps), by code only.

Same brief, same assets → same frames. Nothing here is generated by a model: the scenes' backgrounds come
from Muse Image beforehand (`scene_images`), the app is shown from its REAL screenshots, text is drawn in
the brand font, and an end card closes every video (icon, app name, rating from the store, button).

Per frame: background (brand gradient, a generated scene, or a colour card) → the phone with the real
screen (zoom / pan / pop) → the overlay text (slides in) → crossfade between scenes. Frames are piped to
ffmpeg (`imageio-ffmpeg` ships the binary) as H.264, yuv420p, silent for now.

The product guard: in `screen` scenes the screenshot is only resized (`composer.prepare_product`) and moved;
`screen_layer` is the single place that turns a screenshot into pixels, so a test can replay it.
"""

import math
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path

import imageio_ffmpeg
from PIL import Image, ImageDraw, ImageFilter

from whynot.agents.brief import END_CARD_SECONDS, Scene, VideoBrief
from whynot.create import fonts
from whynot.create.composer import best_text_colour, hex_to_rgb, prepare_product

W, H, FPS = 1080, 1920, 30
FADE_FRAMES = 8
CARD_W = 760  # screenshot card width
CARD_MAX_H = 1260
MIN_RATING_SHOWN = 4.3  # a weaker rating doesn't help an ad; the end card then just says where to get it
RGB = tuple[int, int, int]


@dataclass
class Look:
    """The brand: palette [bg, fg, accent, surface] (from `assets/brand.py`), icon, short name, rating."""

    bg: RGB
    fg: RGB
    accent: RGB
    surface: RGB
    app_name: str
    icon: Image.Image | None = None
    rating: float | None = None
    rating_count: int | None = None

    @classmethod
    def from_palette(cls, palette: list[str], app_name: str, **kw) -> "Look":
        bg, fg, accent, surface = (hex_to_rgb(c) for c in palette[:4])
        return cls(bg, fg, accent, surface, app_name, **kw)


@dataclass
class Assets:
    screens: list[Image.Image]  # the app's real screenshots, in brief numbering (1-based in the brief)
    scenes: dict[int, Image.Image] = field(default_factory=dict)  # scene index (0-based) -> generated background


def ease(t: float) -> float:
    """Ease-in-out on [0, 1]."""
    t = min(1.0, max(0.0, t))
    return t * t * (3 - 2 * t)


def overshoot(t: float) -> float:
    """0 → 1 with a small overshoot (a "pop")."""
    t = min(1.0, max(0.0, t))
    return 1 + 1.7 * (t - 1) ** 3 + 0.7 * (t - 1) ** 2 if t < 1 else 1.0


def gradient(top: RGB, bottom: RGB) -> Image.Image:
    ramp = Image.linear_gradient("L").resize((W, H))
    return Image.composite(Image.new("RGB", (W, H), bottom), Image.new("RGB", (W, H), top), ramp)


def cover(img: Image.Image, scale: float = 1.0, shift: tuple[float, float] = (0, 0)) -> Image.Image:
    """`img` filling the frame (cropped), zoomed by `scale` and shifted by a fraction of the spare room."""
    src = img.convert("RGB")
    s = max(W / src.width, H / src.height) * scale
    big = src.resize((math.ceil(src.width * s), math.ceil(src.height * s)), Image.Resampling.BILINEAR)
    spare_x, spare_y = big.width - W, big.height - H
    x = int(spare_x / 2 + shift[0] * spare_x / 2)
    y = int(spare_y / 2 + shift[1] * spare_y / 2)
    return big.crop((x, y, x + W, y + H))


def screen_layer(screenshot: Image.Image) -> Image.Image:
    """The real screenshot as a big rounded card with a soft shadow (RGBA). No phone frame: store screenshots
    often already show a phone. The screenshot is only resized: product pixels stay true."""
    sw = CARD_W
    sh = round(screenshot.height * sw / screenshot.width)
    if sh > CARD_MAX_H:  # very tall screenshots: fit the height instead
        sh, sw = CARD_MAX_H, round(screenshot.width * CARD_MAX_H / screenshot.height)
    card = prepare_product(screenshot, (sw, sh), radius=44)
    out = Image.new("RGBA", (sw + 160, sh + 180), (0, 0, 0, 0))
    ImageDraw.Draw(out).rounded_rectangle((80, 110, 80 + sw, 110 + sh), radius=44, fill=(0, 0, 0, 80))
    out = out.filter(ImageFilter.GaussianBlur(30))
    out.alpha_composite(card, (80, 80))
    return out


def text_block(text: str, width: int, size: int, colour: RGB, *, box: RGB | None = None,
               min_size: int = 40) -> Image.Image:
    """Bold text wrapped to `width`, shrunk until it fits 3 lines; on a rounded box when `box` is given."""
    probe = ImageDraw.Draw(Image.new("RGB", (1, 1)))
    while True:
        font = fonts.load(size, bold=True)
        lines: list[str] = []
        for word in text.split():
            if lines and probe.textlength(f"{lines[-1]} {word}", font=font) <= width:
                lines[-1] += f" {word}"
            else:
                lines.append(word)
        if len(lines) <= 3 or size <= min_size:
            break
        size -= 6
    line_h = round(size * 1.18)
    tw = max(int(probe.textlength(line, font=font)) for line in lines)
    pad = 36 if box else 0
    img = Image.new("RGBA", (tw + 2 * pad, line_h * len(lines) + 2 * pad - (line_h - size) + 8), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if box:
        d.rounded_rectangle((0, 0, img.width - 1, img.height - 1), radius=34, fill=(*box, 235))
    for i, line in enumerate(lines):
        lw = probe.textlength(line, font=font)
        d.text(((img.width - lw) / 2, pad + i * line_h), line, font=font, fill=colour)
    return img


def place(frame: Image.Image, layer: Image.Image, center: tuple[float, float], *, scale: float = 1.0,
          opacity: float = 1.0) -> None:
    if opacity <= 0 or scale <= 0:
        return
    lay = layer
    if scale != 1.0:
        lay = layer.resize((max(1, round(layer.width * scale)), max(1, round(layer.height * scale))),
                           Image.Resampling.BILINEAR)
    if opacity < 1.0:
        lay = lay.copy()
        lay.putalpha(lay.getchannel("A").point(lambda a: round(a * opacity)))
    frame.alpha_composite(lay, (round(center[0] - lay.width / 2), round(center[1] - lay.height / 2)))


class SceneRenderer:
    """Renders scene `i` of a brief at any time `t` (seconds from the scene start)."""

    def __init__(self, brief: VideoBrief, i: int, look: Look, assets: Assets):
        self.scene: Scene = brief.scenes[i]
        self.first = i == 0
        self.look = look
        s = self.scene
        card_fg = best_text_colour(look.accent, [look.bg, look.fg, look.surface])
        if s.kind == "screen":
            if s.screen is None or not 1 <= s.screen <= len(assets.screens):
                raise ValueError(f"scene {i + 1}: screenshot {s.screen} does not exist")
            self.bg = gradient(look.bg, look.surface).convert("RGBA")
            self.phone = screen_layer(assets.screens[s.screen - 1])
        elif s.kind == "scene":
            if i not in assets.scenes:
                raise ValueError(f"scene {i + 1}: no generated background")
            self.source = assets.scenes[i]
        else:
            self.bg = Image.new("RGBA", (W, H), (*look.accent, 255))
            self.card = text_block(s.text or s.overlay, 900, 120, card_fg)
        # the first scene carries the hook big at the top; its overlay becomes a caption at the bottom
        top_text = brief.hook if self.first else s.overlay
        if s.kind == "scene":  # white text on a photo needs a dark box
            self.top = text_block(top_text, 900, 90 if self.first else 70, (255, 255, 255), box=(0, 0, 0))
        else:
            ink = card_fg if s.kind == "text" else look.fg
            self.top = text_block(top_text, 920, 96 if self.first else 74, ink)
        self.caption = text_block(s.overlay, 900, 58, look.fg, box=look.surface) if self.first else None

    def frame(self, t: float) -> Image.Image:
        s, d = self.scene, self.scene.seconds
        p = t / d
        if s.kind == "scene":
            scale = {"zoom_in": 1.0 + 0.10 * ease(p), "zoom_out": 1.10 - 0.10 * ease(p)}.get(s.motion, 1.04)
            shift = ((ease(p) - 0.5) * 1.2, 0) if s.motion == "pan" else (0, (0.5 - ease(p)) * 0.6 if
                                                                           s.motion == "scroll" else 0)
            frame = cover(self.source, scale, shift).convert("RGBA")
            shade = Image.new("RGBA", (W, H), (0, 0, 0, 0))
            ImageDraw.Draw(shade).rectangle((0, 0, W, 760), fill=(0, 0, 0, 70))
            frame.alpha_composite(shade)
        else:
            frame = self.bg.copy()
        if s.kind == "screen":
            scale, dy = 1.0, 0.0
            if s.motion == "zoom_in":
                scale = 1.0 + 0.06 * ease(p)
            elif s.motion == "zoom_out":
                scale = 1.06 - 0.06 * ease(p)
            elif s.motion == "pop":
                scale = 0.85 + 0.15 * overshoot(min(1.0, t / 0.45))
            elif s.motion in ("scroll", "pan"):
                dy = -140 * ease(p)
            place(frame, self.phone, (W / 2, 1210 + dy), scale=scale)
        elif s.kind == "text":
            k = overshoot(min(1.0, t / 0.4)) if s.motion == "pop" else 1.0
            place(frame, self.card, (W / 2, H / 2 + 60), scale=0.8 + 0.2 * k)
        rise = ease(min(1.0, t / 0.35))
        place(frame, self.top, (W / 2, 330 + 40 * (1 - rise)), opacity=rise)
        if self.caption is not None:
            show = ease(min(1.0, max(0.0, (t - 0.5) / 0.35)))
            place(frame, self.caption, (W / 2, H - 230 + 30 * (1 - show)), opacity=show)
        return frame


class EndCard:
    def __init__(self, brief: VideoBrief, look: Look):
        self.look = look
        self.bg = gradient(look.bg, look.surface).convert("RGBA")
        self.icon = None
        if look.icon is not None:
            icon = look.icon.convert("RGBA").resize((300, 300), Image.Resampling.LANCZOS)
            mask = Image.new("L", icon.size, 0)
            ImageDraw.Draw(mask).rounded_rectangle((0, 0, 299, 299), radius=68, fill=255)
            icon.putalpha(mask)
            self.icon = icon
        self.name = text_block(look.app_name, 900, 84, look.fg)
        good = look.rating is not None and look.rating >= MIN_RATING_SHOWN and (look.rating_count or 0) >= 20
        rating = f"Rated {look.rating:.1f} on the App Store" if good else "On the App Store"
        self.rating = text_block(rating, 900, 44, look.fg)
        btn_fg = best_text_colour(look.accent, [look.bg, look.fg, look.surface])
        label = text_block(brief.cta, 700, 64, btn_fg)
        btn = Image.new("RGBA", (max(560, label.width + 140), label.height + 70), (0, 0, 0, 0))
        ImageDraw.Draw(btn).rounded_rectangle((0, 0, btn.width - 1, btn.height - 1), radius=btn.height // 2,
                                              fill=(*look.accent, 255))
        btn.alpha_composite(label, ((btn.width - label.width) // 2, (btn.height - label.height) // 2))
        self.button = btn

    def frame(self, t: float) -> Image.Image:
        frame = self.bg.copy()
        k = overshoot(min(1.0, t / 0.5))
        gap = 48
        blocks = [b for b in (self.icon, self.name, self.rating, self.button) if b is not None]
        y = (H - sum(b.height for b in blocks) - gap * (len(blocks) - 1)) / 2 - 40
        centers = []
        for b in blocks:
            centers.append(y + b.height / 2)
            y += b.height + gap
        i = 0
        if self.icon is not None:
            place(frame, self.icon, (W / 2, centers[0]), scale=0.7 + 0.3 * k)
            i = 1
        place(frame, self.name, (W / 2, centers[i]), opacity=ease(t / 0.4))
        place(frame, self.rating, (W / 2, centers[i + 1]), opacity=ease((t - 0.2) / 0.4))
        pulse = 1.0 + 0.04 * math.sin(max(0.0, t - 0.6) * 2 * math.pi / 1.2)
        place(frame, self.button, (W / 2, centers[i + 2]), scale=pulse * (0.85 + 0.15 * ease((t - 0.3) / 0.4)),
              opacity=ease((t - 0.3) / 0.3))
        return frame


def frames(brief: VideoBrief, look: Look, assets: Assets) -> Iterator[Image.Image]:
    """Every frame of the video, in order (RGB, 1080×1920)."""
    parts: list[tuple[object, float]] = [(SceneRenderer(brief, i, look, assets), s.seconds)
                                         for i, s in enumerate(brief.scenes)]
    parts.append((EndCard(brief, look), END_CARD_SECONDS))
    prev_last: Image.Image | None = None
    for renderer, seconds in parts:
        n = round(seconds * FPS)
        for k in range(n):
            img = renderer.frame(k / FPS)  # type: ignore[attr-defined]
            if prev_last is not None and k < FADE_FRAMES:
                img = Image.blend(prev_last, img, (k + 1) / (FADE_FRAMES + 1))
            if k == n - 1:
                prev_last = img
            yield img.convert("RGB")


def render(brief: VideoBrief, look: Look, assets: Assets, out: Path, *, poster_at: float = 1.2) -> dict:
    """Write `out` (.mp4) and `<out>.poster.jpg`; returns facts about the file."""
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    writer = imageio_ffmpeg.write_frames(str(out), (W, H), fps=FPS, codec="libx264", pix_fmt_out="yuv420p",
                                         quality=8, macro_block_size=8, ffmpeg_log_level="error")
    writer.send(None)
    count = 0
    poster_frame = round(poster_at * FPS)
    for img in frames(brief, look, assets):
        if count == poster_frame:
            img.save(out.with_suffix(".poster.jpg"), quality=88)
        writer.send(img.tobytes())
        count += 1
    writer.close()
    return {"path": out.name, "frames": count, "seconds": round(count / FPS, 2), "width": W, "height": H,
            "fps": FPS, "bytes": out.stat().st_size}
